// Generates the Apps Script files that are copies of shared sources:
//   apps-script/Index.html   ← public/index.html (page body)
//   apps-script/Styles.html  ← public/styles.css
//   apps-script/App.html     ← public/app.js
//   apps-script/Seed.gs      ← data/export/ (templates and moments from the artifact)
// Edit the sources, then run `npm run build:apps-script`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../", import.meta.url).pathname;
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, s) => writeFileSync(join(root, "apps-script", p), s);
const NOTE = "Generated by scripts/build-apps-script.mjs. Edit the source in public/ or data/ instead.";

const html = read("public/index.html");
const fonts = html.match(/<link rel="preconnect"[^>]*>\n<link rel="stylesheet" href="https:\/\/fonts[^>]*>/)[0];
const body = html.slice(html.indexOf("<body>") + 6, html.indexOf('<script src="db.js">')).trim();
write("Index.html", `<!DOCTYPE html>
<!-- ${NOTE} -->
<html lang="en">
<head>
<base target="_top">
${fonts}
<?!= include('Styles'); ?>
</head>
<body>
${body}
<?!= include('DbClient'); ?>
<?!= include('App'); ?>
</body>
</html>
`);

write("Styles.html", `<!-- ${NOTE} -->\n<style>\n${read("public/styles.css")}</style>\n`);

const app = read("public/app.js");
if (app.includes("</script") || app.includes("<?")) throw new Error("public/app.js contains text that breaks an Apps Script HTML file");
write("App.html", `<!-- ${NOTE} -->\n<script>\n${app}</script>\n`);

const seed = {};
for (const col of readdirSync(join(root, "data/export"))) {
  seed[col] = readdirSync(join(root, "data/export", col))
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => ({ id: f.slice(0, -5), data: JSON.parse(read(join("data/export", col, f))) }));
}
const seedJs = Object.entries(seed)
  .map(([col, docs]) => `  ${col}: [\n${docs.map((d) => "    " + JSON.stringify(d)).join(",\n")},\n  ],`)
  .join("\n");
write("Seed.gs", `// ${NOTE}\n// Templates and moments exported from the Meme Lab artifact; setup() loads them into empty tabs.\nconst SEED_DATA = {\n${seedJs}\n};\n`);

console.log("Wrote apps-script/Index.html, Styles.html, App.html, Seed.gs");
